test('autonomous diagnostic objective → plan → evidence → recommendations → re-run', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Try the live demo' }).click()
  await expect(page.getByRole('heading', { name: /Good .*Demo/ })).toBeVisible({ timeout: 20000 })
  await page.getByRole('link', { name: 'Datasets', exact: false }).first().click()
  await page.getByRole('button', { name: 'Try time-series sample', exact: true }).click()
  await page.getByRole('link', { name: 'Monthly Sales', exact: false }).click()
  await page.getByRole('button', { name: 'Data quality', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Data quality center' })).toBeVisible()
  const reviewing = page.waitForResponse(response => response.url().includes('/quality?target=sales'))
  await page.getByLabel('Review target').selectOption('sales')
  expect((await reviewing).status()).toBe(200)
  await page.getByRole('main').getByRole('button', { name: 'Analyze data', exact: true }).click()
  await page.getByRole('button', { name: 'Continue to objective' }).click()
  await page.getByRole('textbox', { name: 'Analytical objective', exact: true }).fill('Why did sales decrease?')
  await page.getByRole('button', { name: 'Preview analysis plan' }).click()
  await expect(page.getByRole('heading', { name: 'Autonomous Analysis Plan' })).toBeVisible()
  await expect(page.getByRole('dialog').locator('.info-note')).toContainText('Machine learning was not used')
  await page.getByRole('button', { name: 'Start autonomous analysis' }).click()
  await expect(page.getByRole('heading', { name: 'What the evidence tells us' })).toBeVisible({ timeout: 90000 })
  await expect(page.getByText('ML explicitly skipped', { exact: true })).toBeVisible()
  const analyticalUrl = page.url()
  const runId = new URL(analyticalUrl).pathname.split('/').pop()
  await page.goto(`/runs/${runId}?studio=1`)
  await expect(page).toHaveURL(analyticalUrl)
  await expect(page.getByRole('heading', { name: 'What the evidence tells us' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('autonomous-findings-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Objective & plan', exact: true }).click()
  const temporal = page.locator('.analysis-plan li').filter({ hasText: 'Trend and temporal analysis' })
  await temporal.getByText('Why this step?', { exact: true }).click()
  await expect(temporal.getByText(/A valid date column/)).toBeVisible()
  await page.getByRole('button', { name: 'Execution', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Analytical execution trace' })).toBeVisible()
  await expect(page.locator('.analytical-trace li').first()).toBeVisible()
  await page.getByRole('button', { name: 'Statistics & evidence', exact: true }).click()
  await expect(page.getByRole('columnheader', { name: 'Adjusted p', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Recommendations', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Evidence-backed next steps' })).toBeVisible()
  await expect(page.locator('.recommendation-record').first()).toBeVisible()
  await page.getByRole('button', { name: 'Report', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download evidence package' }).click()
  expect((await downloading).suggestedFilename()).toBe('analytiq-analysis.zip')
  const originalUrl = page.url()
  await page.getByRole('button', { name: 'Re-run analysis', exact: true }).click()
  await expect.poll(() => page.url()).not.toBe(originalUrl)
  await expect(page.getByRole('heading', { name: 'What the evidence tells us' })).toBeVisible({ timeout: 90000 })
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: /Experiments/ }).click()
  await expect(page.getByRole('link', { name: 'Why did sales decrease?', exact: true })).toHaveCount(2)
})

